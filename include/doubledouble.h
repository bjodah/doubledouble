inline DoubleDouble hypot(const DoubleDouble& x, const DoubleDouble &y)
{
    if (isinf(x.upper) || isinf(y.upper)) {
        return dd_inf;
    }
    auto absx = x.abs();
    auto absy = y.abs();
    auto m = (absx > absy) ? absx : absy;
    if (m.upper == 0.0 && m.lower == 0.0) {
        return dd_zero;
    }
    auto u = x/m;
    auto v = y/m;
    return m*(u*u + v*v).sqrt();
}

