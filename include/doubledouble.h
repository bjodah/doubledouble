inline DoubleDouble sin_taylor(DoubleDouble const& x)
{
    if (is_zero(x)) {
        return dd_zero;
    }
    const DoubleDouble x2 = x*x;
    const DoubleDouble poly =
        DoubleDouble(1.0) + x2 * (
            -sin_inv_fact[0] + x2 * (
                sin_inv_fact[1] + x2 * (
                    -sin_inv_fact[2] + x2 * (
                        sin_inv_fact[3] + x2 * (
                            -sin_inv_fact[4] + x2 * (
                                sin_inv_fact[5] + x2 * (
                                    -sin_inv_fact[6] + x2 *
                                    sin_inv_fact[7]
                                )
                            )
                        )
                    )
                )
            )
        );
    return x * poly;
}

inline DoubleDouble cos_taylor(DoubleDouble const& x)
{
    if (is_zero(x)) {
        return dd_one;
    }
    const DoubleDouble x2 = x*x;
    return DoubleDouble(1.0) + x2 * (
        -cos_inv_fact[0] + x2 * (
            cos_inv_fact[1] + x2 * (
                -cos_inv_fact[2] + x2 * (
                    cos_inv_fact[3] + x2 * (
                        -cos_inv_fact[4] + x2 * (
                            cos_inv_fact[5] + x2 * (
                                -cos_inv_fact[6] + x2 * (
                                    cos_inv_fact[7] + x2 *
                                    -cos_inv_fact[8]
                                )
                            )
                        )
                    )
                )
            )
        )
    );
}

inline DoubleDouble cosm1_taylor(DoubleDouble const& x)
{
    if (is_zero(x)) {
        return dd_zero;
    }
    const DoubleDouble x2 = x*x;
    return x2 * (
        -cos_inv_fact[0] + x2 * (
            cos_inv_fact[1] + x2 * (
                -cos_inv_fact[2] + x2 * (
                    cos_inv_fact[3] + x2 * (
                        -cos_inv_fact[4] + x2 * (
                            cos_inv_fact[5] + x2 * (
                                -cos_inv_fact[6] + x2 * (
                                    cos_inv_fact[7] + x2 *
                                    -cos_inv_fact[8]
                                )
                            )
                        )
                    )
                )
            )
        )
    );
}

